-- Schema-only export from the supplied School Library Derby database.
-- Application schema owner is normalized to KGL.
-- No student, librarian, or circulation records are included.
CREATE SCHEMA KGL AUTHORIZATION KGL;
SET SCHEMA KGL;

CREATE TABLE AUTHOR (
    AUTHOR_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    AUTHOR_NAME VARCHAR(150),
    NATIONALITY VARCHAR(100),
    CONSTRAINT PK_AUTHOR PRIMARY KEY (AUTHOR_ID)
);

CREATE TABLE BOOK (
    BOOK_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    BOOK_TYPE VARCHAR(100),
    BOOK_CODE VARCHAR(200),
    TITLE VARCHAR(200),
    ISBN VARCHAR(100),
    PUBLICATION_YEAR INTEGER,
    AUTHOR_ID BIGINT,
    CATEGORY_ID BIGINT,
    STATUS VARCHAR(100),
    COMMENT VARCHAR(200),
    REGISTRATION_DATE DATE,
    CONSTRAINT PK_BOOK PRIMARY KEY (BOOK_ID)
);

CREATE TABLE CATEGORY (
    CATEGORY_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    CATEGORY_NAME VARCHAR(100),
    DESCRIPTION VARCHAR(255),
    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID)
);

CREATE TABLE CLASS_NAME (
    CLASS_NAME_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    CLASS_NAME VARCHAR(30),
    CONSTRAINT PK_CLASS_NAME PRIMARY KEY (CLASS_NAME_ID)
);

CREATE TABLE COMPUTER (
    COMPUTER_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    MARK_NAME VARCHAR(100),
    SERIAL_NUMBER VARCHAR(100),
    COMPUTER_DESCRIPTION VARCHAR(200),
    STATUS VARCHAR(50),
    SPECIFICATIONS VARCHAR(200),
    CONSTRAINT PK_COMPUTER PRIMARY KEY (COMPUTER_ID)
);

CREATE TABLE DEPARTMENT (
    DEPARTMENT_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    DEPARTMENT_NAME VARCHAR(30),
    CONSTRAINT PK_DEPARTMENT PRIMARY KEY (DEPARTMENT_ID)
);

CREATE TABLE ISSUEDBOOK (
    ISSUED_BOOK_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    STUDENT_ID BIGINT,
    BOOK_ID BIGINT,
    LIBRARIAN_ID BIGINT,
    ISSUE_DATE DATE,
    DUE_DATE DATE,
    RETURN_DATE DATE,
    STATUS VARCHAR(50),
    RECEIVER_ID BIGINT,
    RETURN_DESCRIPTION VARCHAR(200),
    BORROW_STATUS VARCHAR(200),
    CONSTRAINT PK_ISSUEDBOOK PRIMARY KEY (ISSUED_BOOK_ID)
);

CREATE TABLE ISSUEDCOMPUTER (
    ISSUED_COMPUTER_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    STUDENT_ID BIGINT,
    COMPUTER_ID BIGINT,
    LIBRARIAN_ID BIGINT,
    ISSUE_DATE DATE,
    DUE_DATE DATE,
    RETURN_DATE DATE,
    STATUS VARCHAR(50),
    RECEIVER_ID BIGINT,
    RETURN_DESCRIPTION VARCHAR(200),
    BORROW_STATUS VARCHAR(200),
    CONSTRAINT PK_ISSUEDCOMPUTER PRIMARY KEY (ISSUED_COMPUTER_ID)
);

CREATE TABLE LIBRARIAN (
    LIBRARIAN_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    EMAIL VARCHAR(100),
    USER_CATEGORY VARCHAR(100),
    USERNAME VARCHAR(100),
    PASSWORD VARCHAR(100),
    CONSTRAINT PK_LIBRARIAN PRIMARY KEY (LIBRARIAN_ID)
);

CREATE TABLE PENALITY1 (
    PENALITY1_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    DAYS_LATE INTEGER,
    BOOK_ID BIGINT,
    ISSUED_BOOK_ID BIGINT,
    STUDENT_ID BIGINT,
    FINE_PERIOD DOUBLE,
    FINE_END_DATE DOUBLE,
    CONSTRAINT PK_PENALITY1 PRIMARY KEY (PENALITY1_ID)
);

CREATE TABLE PENALITY2 (
    PENALITY2_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    DAYS_LATE INTEGER,
    COMPUTER_ID BIGINT,
    ISSUED_COMPUTER_ID BIGINT,
    STUDENT_ID BIGINT,
    FINE_PERIOD DOUBLE,
    FINE_END_DATE DOUBLE,
    CONSTRAINT PK_PENALITY2 PRIMARY KEY (PENALITY2_ID)
);

CREATE TABLE STUDENT (
    STUDENT_ID BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1) NOT NULL,
    REG_NUMBER VARCHAR(10),
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    EMAIL VARCHAR(150),
    PHONE VARCHAR(20),
    CLASS_NAME_ID BIGINT,
    DEPARTMENT_ID BIGINT,
    REGISTRATION_DATE DATE,
    STATUS VARCHAR(100),
    CONSTRAINT PK_STUDENT PRIMARY KEY (STUDENT_ID)
);

-- Non-unique indexes present in the source database.
CREATE INDEX IX_BOOK_BOOK_CODE ON BOOK (BOOK_CODE);
CREATE INDEX IX_COMPUTER_SERIAL_NUMBER ON COMPUTER (SERIAL_NUMBER);
CREATE INDEX IX_STUDENT_REG_NUMBER ON STUDENT (REG_NUMBER);

