   public void saveMemberForm() {

    // ===============================
    // 1. FORM VALIDATION
    // ===============================

    if (jTextField1.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter First Name");
        jTextField1.requestFocus();
        return;
    }

    if (jTextField2.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Last Name");
        jTextField2.requestFocus();
        return;
    }

    if (jTextField3.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Email");
        jTextField3.requestFocus();
        return;
    }

    if (jComboBox1.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(null, "Select Permission");
        jComboBox1.requestFocus();
        return;
    }

    if (jTextField6.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Username");
        jTextField6.requestFocus();
        return;
    }

    if (jTextField7.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Password");
        jTextField7.requestFocus();
        return;
    }

    // ===============================
    // 2. INSERT DATA
    // ===============================

    String sql =
        "INSERT INTO LIBRARIAN " +
        "(FIRST_NAME,LAST_NAME,EMAIL,USER_CATEGORY,USERNAME,PASSWORD) " +
        "VALUES(?,?,?,?,?,?)";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, jTextField1.getText().trim());
        pst.setString(2, jTextField2.getText().trim());
        pst.setString(3, jTextField3.getText().trim());
        pst.setString(4, jComboBox1.getSelectedItem().toString().trim());
        pst.setString(5, jTextField6.getText().trim());
        pst.setString(6, jTextField7.getText().trim());

        pst.executeUpdate();

        JOptionPane.showMessageDialog(null, "LIBRARIAN SAVED WELL.");

        // OPTIONAL: clear form
        clearForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null,
                "LIBRARIAN NOT SAVED: " + e);
    }
}
