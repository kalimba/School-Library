public void saveAllForm(String tableName,
                        String column,
                        String value) {

    // =========================
    // 1. VALIDATION
    // =========================

    if (value == null || value.trim().isEmpty()) {
        JOptionPane.showMessageDialog(null,
                "Value cannot be empty for " + tableName);
        return;
    }

    // Optional: prevent bad input
    value = value.trim().toUpperCase();

    // =========================
    // 2. INSERT QUERY
    // =========================

    String sql =
        "INSERT INTO " + tableName +
        " (" + column + ") VALUES (?)";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, value);
        pst.executeUpdate();

        JOptionPane.showMessageDialog(null,
                tableName + " SAVED WELL.");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null,
                tableName + " NOT SAVED: " + e);
    }
}
