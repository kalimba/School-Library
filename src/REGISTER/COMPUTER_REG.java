public void saveComputerForm() {

    // ==========================
    // 1. FORM VALIDATION
    // ==========================

    if (jTextMARK.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Mark Name");
        jTextMARK.requestFocus();
        return;
    }

    if (jTextSERIAL.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Serial Number");
        jTextSERIAL.requestFocus();
        return;
    }

    if (jTextSPES.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Specifications");
        jTextSPES.requestFocus();
        return;
    }

    if (jTextDESCRIPTION.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(null, "Enter Description");
        jTextDESCRIPTION.requestFocus();
        return;
    }

    // ==========================
    // 2. INSERT DATA
    // ==========================

    String sql =
        "INSERT INTO COMPUTER " +
        "(MARK_NAME, SERIAL_NUMBER, SPECIFICATIONS, COMPUTER_DESCRIPTION) " +
        "VALUES(?,?,?,?)";

    try (PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, jTextMARK.getText().trim());
        pst.setString(2, jTextSERIAL.getText().trim());
        pst.setString(3, jTextSPES.getText().trim());
        pst.setString(4, jTextDESCRIPTION.getText().trim());

        pst.executeUpdate();

        JOptionPane.showMessageDialog(null, "COMPUTER SAVED WELL.");

        clearComputerForm();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null,
                "COMPUTER NOT SAVED: " + e);
    }
}
